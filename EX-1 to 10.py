# 2. Compute Entropy and Info Gain
def entropy(col):
    vals, counts = np.unique(col, return_counts=True)
    probs = counts / len(col)
    return -np.sum(probs * np.log2(probs))

def info_gain(df, attribute, target='Play'):
    total_ent = entropy(df[target])
    vals, counts = np.unique(df[attribute], return_counts=True)
    weighted_ent = 0
    for val, cnt in zip(vals, counts):
        sub_df = df[df[attribute] == val]
        weighted_ent += (cnt / len(df)) * entropy(sub_df[target])
    return total_ent - weighted_ent

# 3. Build ID3 Tree
def build_tree(df, attributes, target='Play'):
    target_vals = df[target].unique()
    if len(target_vals) == 1:
        return target_vals[0]
    if len(attributes) == 0:
        return df[target].mode()[0]

    gains = [info_gain(df, attr, target) for attr in attributes]
    best_attr = attributes[np.argmax(gains)]

    tree = {best_attr: {}}
    remaining_attrs = [a for a in attributes if a != best_attr]

    for val in df[best_attr].unique():
        sub_df = df[df[best_attr] == val]
        tree[best_attr][val] = build_tree(sub_df, remaining_attrs, target)
    return tree

attributes = list(df_tree.columns[:-1])
