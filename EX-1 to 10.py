# 1. Custom Linear Regression Class (Gradient Descent from scratch)
class CustomLinearRegression:
    def __init__(self, learning_rate=0.01, num_iterations=1000):
        self.lr = learning_rate
        self.num_iterations = num_iterations
        self.weight = None
        self.bias = None
        self.loss_history = []

    # Mean Squared Error Loss
    def _compute_loss(self, y_true, y_pred):
        return np.mean((y_true - y_pred) ** 2)

    def fit(self, X, y):
        n_samples = len(X)
        # Initialize parameters
        self.weight = 0.0
        self.bias = 0.0
        self.loss_history = []

        for epoch in range(self.num_iterations):
            # Line prediction equation: y = w*x + b
            y_predicted = self.weight * X + self.bias

            # Save the current Mean Squared Error
            loss = self._compute_loss(y, y_predicted)
            self.loss_history.append(loss)

            # Calculate Gradients
            dw = (-2 / n_samples) * np.sum(X * (y - y_predicted))
            db = (-2 / n_samples) * np.sum(y - y_predicted)

            # Update weights and bias
            self.weight -= self.lr * dw
            self.bias -= self.lr * db

    def predict(self, X):
        return self.weight * X + self.bias

