print("Built ID3 Decision Tree structure:", id3_tree)

# 4. Classify a new sample
def predict(tree, sample):
    if not isinstance(tree, dict):
        return tree
    root = list(tree.keys())[0]
    val = sample.get(root)
    if val in tree[root]:
        return predict(tree[root][val], sample)
    return "No"

