# 1. Custom Gaussian Probability Density Function
def gaussian_pdf(x, mean, var):
    coeff = 1.0 / np.sqrt(2 * np.pi * var)
    exponent = np.exp(-((x - mean) ** 2) / (2 * var))
    return coeff * exponent

# 2. Expectation-Maximization for 2-Component Gaussian Mixture Model
class EM_GMM:
    def __init__(self, n_iterations=100):
        self.n_iterations = n_iterations
        self.log_likelihoods = []

    def fit(self, X):
        # Initialize parameters
        # Two clusters/components
        self.pi = 0.5  # Mixing coefficient (prior probability for Cluster 1)
        self.mu1 = np.percentile(X, 25) # Initial mean for Cluster 1
        self.mu2 = np.percentile(X, 75) # Initial mean for Cluster 2
        self.var1 = np.var(X)
        self.var2 = np.var(X)

        n_samples = len(X)
        self.log_likelihoods = []

        for step in range(self.n_iterations):
            # --- E-STEP: Compute Responsibilities ---
            pdf1 = gaussian_pdf(X, self.mu1, self.var1)
            pdf2 = gaussian_pdf(X, self.mu2, self.var2)

            # Weighted probability of belonging to either component
            weighted_prob1 = self.pi * pdf1
            weighted_prob2 = (1 - self.pi) * pdf2
            total_prob = weighted_prob1 + weighted_prob2

            # Responsibilities (gamma)
            gamma1 = weighted_prob1 / total_prob
            gamma2 = weighted_prob2 / total_prob

            # Track Log-Likelihood
            log_likelihood = np.sum(np.log(total_prob))
            self.log_likelihoods.append(log_likelihood)

            # --- M-STEP: Update Parameters based on Responsibilities ---
            N1 = np.sum(gamma1)
            N2 = np.sum(gamma2)

            # Update Means
            self.mu1 = np.sum(gamma1 * X) / N1
            self.mu2 = np.sum(gamma2 * X) / N2

            # Update Variances
            self.var1 = np.sum(gamma1 * (X - self.mu1) ** 2) / N1
            self.var2 = np.sum(gamma2 * (X - self.mu2) ** 2) / N2

            # Update Mixing Coefficient
            self.pi = N1 / n_samples

    def predict_responsibilities(self, X):
        pdf1 = gaussian_pdf(X, self.mu1, self.var1)
        pdf2 = gaussian_pdf(X, self.mu2, self.var2)
        weighted_prob1 = self.pi * pdf1
        weighted_prob2 = (1 - self.pi) * pdf2
        total_prob = weighted_prob1 + weighted_prob2
        return weighted_prob1 / total_prob, weighted_prob2 / total_prob

