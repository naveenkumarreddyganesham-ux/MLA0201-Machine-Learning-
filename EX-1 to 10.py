# 1. Custom polynomial feature transformer from scratch
def get_polynomial_features(X, degree):
    # Reshape X to a column vector if it is 1D
    if len(X.shape) == 1:
        X = X.reshape(-1, 1)

    n_samples = X.shape[0]
    # Create an array of shape (n_samples, degree)
    poly_features = np.zeros((n_samples, degree))
    for d in range(1, degree + 1):
        poly_features[:, d-1] = (X ** d).squeeze()
    return poly_features

# 2. Custom Regression Class using the Normal Equation (OLS)
class CustomRegression:
    def __init__(self):
        self.theta = None

    def fit(self, X, y):
        # Add intercept term (column of 1s)
        X_b = np.c_[np.ones((len(X), 1)), X]
        # Solve for coefficients using the Normal Equation: theta = (X^T * X)^(-1) * X^T * y
        self.theta = np.linalg.inv(X_b.T.dot(X_b)).dot(X_b.T).dot(y)

    def predict(self, X):
        X_b = np.c_[np.ones((len(X), 1)), X]
        return X_b.dot(self.theta)

