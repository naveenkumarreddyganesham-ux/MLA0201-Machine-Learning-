def plot_node(node, x, y, dx, parent_coord=None, branch_val=None):
    if not isinstance(node, dict):
        # Leaf Node
        ax.text(x, y, f"Leaf:\n{node}", bbox=dict(boxstyle='round,pad=0.5', facecolor='lightgreen', edgecolor='black'), ha='center', va='center', fontsize=10)
